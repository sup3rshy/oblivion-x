"""Obfuscation detection + static deobfuscation (Oblivion taxonomy).

Detects the four technique families from Section 2.4 of the Oblivion paper
and statically recovers payloads hidden by the recoverable ones
(Chr arithmetic, literal concatenation, Base64), feeding the E3 experiment
(unobfuscated vs obfuscated observability).
"""
from __future__ import annotations

import ast
import base64
import math
import re
import string
from typing import Dict, List, Optional, Tuple

# ---------------------------------------------------------------------------
# Detection
# ---------------------------------------------------------------------------

def shannon_entropy(s: str) -> float:
    if not s:
        return 0.0
    freq = {c: s.count(c) for c in set(s)}
    n = len(s)
    return -sum((v / n) * math.log2(v / n) for v in freq.values())


def detect_obfuscation(source: str) -> Dict[str, bool]:
    """Return per-technique boolean flags."""
    code = _strip_comments(source)
    flags = {
        "random": False,
        "split": False,
        "encode": False,
        "logic": False,
    }
    # split: many short literals joined with &. Plain code contains some
    # concatenation too, so require a clear excess of short pieces over long
    # literals (the split transform turns every long literal into pieces).
    n_concat = len(re.findall(r'"[^"]{0,12}"\s*&', code))
    n_long = len(re.findall(r'"[^"]{16,}"', code))
    if n_concat >= 5 and n_concat >= n_long:
        flags["split"] = True
    # encode: Chr/Asc/Hex chains or a Base64 blob. A handful of Chr(34)
    # calls is normal quoting, so require a chain (>= 5 calls) or a blob.
    n_chr = len(re.findall(r"\b(?:Chr|ChrW|Chr\$|ChrW\$)\s*\(", code, re.I))
    n_hex = len(re.findall(r"\b(?:Asc|Hex)\s*\(", code, re.I))
    if n_chr >= 5 or n_hex >= 3:
        flags["encode"] = True
    if re.search(r"[A-Za-z0-9+/]{40,}={0,2}", code):
        flags["encode"] = True
    # random: several long lowercase identifiers containing digits, as
    # produced by identifier randomization. Ordinary VBA names (objShell,
    # outPath) have no digits, and logic-junk names have no digits either.
    names = {t for t in re.findall(r"\b[a-z][a-z0-9]{7,}\b", code)
             if any(ch.isdigit() for ch in t)}
    if len(names) >= 2:
        flags["random"] = True
    # logic: unreachable branches only. Do not key on words like "decoy" or
    # "junk": benign code and encode-variant helpers use such names.
    if re.search(r"If\s+(False|1\s*=\s*2|0\s*=\s*1)\b", code, re.I):
        flags["logic"] = True
    return flags


def _strip_comments(source: str) -> str:
    out = []
    for line in source.splitlines():
        # Attribute lines are compile-time metadata generated by Office and
        # contain long literals; they must not influence the heuristics.
        if line.lstrip().lower().startswith("attribute"):
            continue
        # strip single-quote comments (outside strings, naive but adequate)
        if "'" in line:
            in_str = False
            buf = []
            for ch in line:
                if ch == '"':
                    in_str = not in_str
                    buf.append(ch)
                elif ch == "'" and not in_str:
                    break
                else:
                    buf.append(ch)
            line = "".join(buf)
        out.append(line)
    return "\n".join(out)


# ---------------------------------------------------------------------------
# Static deobfuscation
# ---------------------------------------------------------------------------

def eval_const_expr(expr: str) -> Optional[str]:
    """Evaluate simple VBA constant expressions: Chr(n) & Chr(m) ...,
    "lit" & "lit", arithmetic inside Chr()."""
    expr = expr.strip()
    try:
        def repl_chr(m: "re.Match") -> str:
            n = m.group(1).strip()
            # allow simple arithmetic like 113 - 1
            val = _eval_int(n)
            return repr(chr(val))
        expr2 = re.sub(r"Chr(W)?\$?\s*\(\s*([^()]+)\s*\)", repl_chr, expr)
        # translate & to +
        expr2 = expr2.replace("&", "+")
        node = ast.parse(expr2, mode="eval")
        val = eval(compile(node, "<vba>", "eval"), {"__builtins__": {}})
        return str(val)
    except Exception:
        return None


def _eval_int(expr: str) -> int:
    expr = expr.strip().replace("&", "+")
    try:
        node = ast.parse(expr, mode="eval")
        return int(eval(compile(node, "<vba>", "eval"), {"__builtins__": {}}))
    except Exception:
        raise ValueError("not an int expr")


def eval_concat_expr(expr: str) -> Optional[str]:
    """Evaluate "a" & "b" & "c" literal concatenations."""
    parts = [p.strip() for p in expr.split("&")]
    out = ""
    for p in parts:
        if re.fullmatch(r'"[^"]*"', p):
            out += p[1:-1]
        else:
            return None
    return out


def decode_base64_blobs(source: str) -> List[Tuple[str, bytes]]:
    out = []
    for m in re.finditer(r'"([A-Za-z0-9+/]{20,}={0,2})"', source):
        try:
            raw = base64.b64decode(m.group(1))
            if all(32 <= b < 127 or b in (9, 10, 13) for b in raw):
                out.append((m.group(1), raw))
        except Exception:
            continue
    return out


def recover_payloads(source: str) -> List[str]:
    """Statically recover hidden strings: Chr chains, split literals,
    Base64 blobs. Returns the list of recovered strings."""
    found: List[str] = []
    # Chr(...) & Chr(...) chains
    for m in re.finditer(
            r"((?:Chr(W)?\$?\s*\([^)]*\)\s*&?\s*){2,})", source):
        val = eval_const_expr(m.group(1))
        if val:
            found.append(val)
    # literal concatenations
    for m in re.finditer(r'(?:"[^"]*"\s*&\s*){2,}"[^"]*"', source):
        val = eval_concat_expr(m.group(0))
        if val:
            found.append(val)
    # base64
    for b64, raw in decode_base64_blobs(source):
        found.append(raw.decode("latin-1"))
    return found
